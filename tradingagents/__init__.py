# ============================================================================
# 【前置知识】
# ============================================================================
#
# 本文件是 tradingagents 核心包的初始化文件（__init__.py）。
# 以下是需要了解的核心概念：
#
# 1. Python 包（Package）与 __init__.py：
#    - 在 Python 中，包含 __init__.py 文件的目录被称为"包"（Package）。
#    - 当使用 import 语句导入包时，__init__.py 会自动执行。
#    - __init__.py 用于：
#      * 初始化包级状态
#      * 设置环境变量
#      * 导入子模块
#      * 定义包的公开接口
#    - 类比：__init__.py 就像一个商店的"开业仪式"——
#      在正式营业（使用包的功能）之前，先做好准备工作。
#
# 2. os 模块（操作系统接口）：
#    - Python 标准库，提供与操作系统交互的功能。
#    - os.environ：一个字典对象，存储当前进程的所有环境变量。
#    - os.environ.setdefault(key, value)：如果环境变量不存在，则设置它。
#      与 os.environ[key] = value 的区别：
#      - setdefault：只在变量不存在时设置（不会覆盖已有值）
#      - 直接赋值：总是设置（会覆盖已有值）
#    - os.path：子模块，提供路径操作功能（如拼接、获取绝对路径等）
#
# 3. 环境变量（Environment Variable）：
#    - 环境变量是操作系统级别的配置，用键值对存储（如 PATH=/usr/bin）。
#    - Python 程序可以通过 os.environ 读取和设置环境变量。
#    - 环境变量在程序启动时从操作系统继承，所有线程共享。
#    - 常见用途：
#      * API 密钥（如 OPENAI_API_KEY）
#      * 编码设置（如 PYTHONUTF8=1）
#      * 路径配置（如 PATH）
#
# 4. UTF-8 编码与 PYTHONUTF8：
#    - UTF-8 是一种字符编码方式，支持世界上几乎所有语言的字符。
#    - Python 3 默认使用 UTF-8，但在 Windows 系统上可能默认使用其他编码（如 GBK）。
#    - 设置 PYTHONUTF8=1 强制 Python 使用 UTF-8 编码：
#      * 避免中文等多字节字符的乱码问题
#      * 确保文件读写、终端输出使用一致的编码
#    - 这是 Windows 平台兼容性的重要设置。
#
# 5. 本文件的运行时数据流：
#    用户运行 import tradingagents（或任何 tradingagents 子模块）
#    → Python 解释器找到 tradingagents 目录
#    → 检查 __init__.py 文件并执行
#    → os.environ.setdefault("PYTHONUTF8", "1") 被执行
#      → 检查 PYTHONUTF8 环境变量是否已设置
#      → 如果已设置（如用户在系统中已配置），不覆盖
#      → 如果未设置，设置为 "1"（强制 UTF-8 模式）
#    → 后续所有子模块导入时，Python 已处于 UTF-8 模式
#    → 文件读写、终端输出使用 UTF-8 编码，避免乱码
# ============================================================================

# os 模块：Python 标准库，提供操作系统接口
# os.environ：环境变量字典，存储当前进程的所有环境变量
# os.environ.setdefault(key, value)：设置环境变量（如果不存在）
# os.path：路径操作子模块（本文件未使用，但 tradingagents 包中其他模块广泛使用）
import os

# 设置默认环境变量 PYTHONUTF8=1
# 这确保 Python 在 Windows 系统上使用 UTF-8 编码处理文本
# 对于中文等多字节字符的处理非常重要，避免出现乱码问题
# setdefault 与普通赋值不同：如果该环境变量已经被设置过，则不会覆盖
# 这意味着用户可以在系统中预先设置 PYTHONUTF8=0 来禁用此行为
# 环境变量值始终是字符串类型，所以用 "1" 而非 1
os.environ.setdefault("PYTHONUTF8", "1")
