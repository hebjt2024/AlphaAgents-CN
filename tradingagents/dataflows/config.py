# =============================================================================
# 模块名称：config.py
# 模块功能：全局配置管理模块
# =============================================================================
#
# ============================================================================
# 前置知识（如果你完全没有 Python 经验，请先阅读本节）
# ============================================================================
#
# 【什么是"全局配置"？为什么需要它？】
#   一个稍大型的程序通常有很多"可变参数"：用哪个数据源、API 密钥是什么、
#   超时时间设几秒、数据缓存到哪里……这些参数如果写死在代码里，每次想改
#   都得修改源代码，非常不方便。
#
#   "配置管理"就是把这些可变参数集中到一个地方（配置字典），统一管理。
#   想改参数时，只需改配置，不用动代码逻辑。
#
#   在 TradingAgents 中，配置决定了：
#   - 每类数据从哪个供应商获取（如基本面数据用 yfinance）
#   - 缓存文件的保存路径
#   - 是否打印调试日志
#   - 等等……
#
# 【什么是字典（dict）？】
#   Python 的字典是"键值对"集合：{"键1": 值1, "键2": 值2}
#   配置就是一个字典，例如：
#     {
#       "data_vendors": {"fundamental_data": "yfinance"},
#       "cache_dir": "/tmp/cache"
#     }
#   用 config["data_vendors"] 可以取出对应的值。
#
# 【什么是"单例模式"（Singleton Pattern）？】
#   "单例"就是"全局只有一个实例"。
#   想象一个公司只有一个CEO。不管你在哪个部门，提到"CEO"都是同一个人。
#
#   在程序里，配置只需要一份。如果每个模块各自创建一份配置，
#   可能会出现不一致（A模块改了配置，B模块不知道）。
#   单例模式确保所有模块共享同一份配置。
#
#   Python 实现单例最简单的方式就是用"模块级变量"：
#   - 一个 .py 文件就是一个模块
#   - Python 保证模块在首次被 import 时只执行一次
#   - 所以模块级的变量天然就是"全局唯一"的
#   本模块用 _config 这个模块级变量来存储唯一的配置实例。
#
# 【什么是"延迟初始化"（Lazy Initialization）？】
#   "延迟初始化"就是"用到的时候才创建，不用就不创建"。
#   就像你不会在搬家当天就把所有家具买齐，而是需要什么才买什么。
#
#   本模块初始时 _config = None（还没创建），等到第一次有人调用
#   get_config() 时才真正加载默认配置。这样如果某些场景根本
#   不需要配置，就不会浪费资源去初始化。
#
# 【什么是 None？】
#   None 是 Python 里表示"什么都没有"的特殊值，类似其他语言的 null。
#   这里用 None 表示"配置还没被加载"。
#
# 【什么是 global 关键字？】
#   在函数内部，Python 默认认为你赋值的变量是"局部变量"（只在函数内有效）。
#   如果你想在函数内修改"模块级别的全局变量"，必须先用 global 声明。
#   【通俗比喻】global 就像告诉 Python："我要改的是公共黑板上的内容，
#   不是在我自己本子上写字。"
#
# 【什么是 .copy()（浅拷贝）？】
#   .copy() 复制一个字典，得到一个内容相同但独立的新字典。
#   修改新字典不会影响原字典。这里用 copy 是为了：
#   - 初始化时复制默认配置，避免修改了默认配置的原始数据
#   - 返回时复制配置，避免调用方修改影响全局配置
# ============================================================================
#
# 设计模式说明：
#   - 模块级单例（Module-level Singleton）：通过模块级别的全局变量 _config
#     来存储唯一的配置实例。Python 中模块在首次导入时只执行一次，因此这种
#     方式天然实现了单例效果。
#   - 延迟初始化（Lazy Initialization）：配置在首次调用 get_config() 时
#     才被初始化，而不是在模块导入时立即初始化，节省了不必要的资源开销。
#
# ============================================================================
# 运行时数据流示例
# ============================================================================
#
#   场景：用户启动 TradingAgents 分析苹果股票
#
#   第 1 步：模块被导入
#     某个模块执行 `from tradingagents.dataflows.config import get_config`
#     → Python 首次导入 config.py 模块
#     → 模块底部 `initialize_config()` 被执行
#     → _config 从 None 变为 default_config.DEFAULT_CONFIG 的副本
#
#   第 2 步：用户自定义配置
#     用户代码调用 set_config({"data_vendors": {"fundamental_data": "alpha_vantage"}})
#     → _config.update(...) 将自定义配置合并进去
#     → 此后基本面数据将从 Alpha Vantage 获取
#
#   第 3 步：其他模块读取配置
#     interface.py 调用 get_config()
#     → 返回 _config 的副本（保护原始配置）
#     → interface.py 从副本中读取 data_vendors 来决定供应商
#
# =============================================================================

# ---------------------------------------------------------------------------
# 导入依赖
# ---------------------------------------------------------------------------

# 导入默认配置字典。这个字典包含了所有配置项的默认值。
# default_config 是项目中另一个模块，定义了基础的配置项（如数据源、缓存路径等）。
# 【什么是 import as？】给模块起个短别名，后续用 default_config.DEFAULT_CONFIG
# 来引用，比写完整路径更简洁。
# 从 typing 模块导入 Dict 和 Optional 类型注解。
# 【什么是类型注解？】给变量标注类型，方便人和 IDE 理解。Python 运行时不强制检查。
# Dict: 用于声明字典类型，例如 Dict[str, int] 表示键为字符串、值为整数的字典。
# Optional: 用于声明一个变量可以是某种类型或 None。
#   例如 Optional[int] 等价于 int | None（Python 3.10+ 的联合类型语法）。
#   Optional[X] 就是"X 类型或者 None"的意思。

import tradingagents.default_config as default_config

# ---------------------------------------------------------------------------
# 全局配置变量
# ---------------------------------------------------------------------------

# _config: 存储全局配置的模块级私有变量。
# 命名规则说明：
#   - 变量名以单下划线 "_" 开头，在 Python 中这是一种约定，表示该变量是
#     "模块私有的"（module-private），即不希望在模块外部被直接访问。
#     【什么是约定？】Python 不会强制阻止你访问 _ 开头的变量，
#     但这是一种"君子协定"：开发者看到 _ 开头就知道"这是内部用的，别从外面碰"。
#   - 类型注解 Optional[Dict] 表示这个变量可以是 Dict（字典）类型或 None。
#     初始值为 None，表示配置尚未被初始化。
# 设计意图：
#   使用 None 初始值实现"延迟初始化"——只有在真正需要配置时才加载默认值，
#   避免在模块导入阶段就执行不必要的初始化操作。
_config: dict | None = None


# ---------------------------------------------------------------------------
# 函数：initialize_config
# ---------------------------------------------------------------------------
def initialize_config():
    """
    初始化配置：使用默认配置填充全局 _config 变量。

    功能说明：
      如果 _config 尚未被初始化（即仍为 None），则从 default_config 模块
      复制默认配置字典。如果已经初始化过，则跳过（幂等操作）。

      【什么是"幂等"（Idempotent）？】
        幂等是指"执行多次和执行一次效果一样"。
        initialize_config() 调用 100 次，结果和调用 1 次一样——
        因为第二次开始 _config 已经不是 None，会直接跳过。

    关键概念：
      - global 关键字：
        在函数内部，如果要对模块级别的全局变量进行赋值操作（不是读取），
        必须使用 global 关键字声明。否则 Python 会认为你是在创建一个
        同名的局部变量，而不是修改全局变量。
        语法：global 变量名
        注意：如果只是读取全局变量（如 if _config is None），不需要 global。

      - .copy() 方法：
        字典的 copy() 方法创建一个"浅拷贝"（shallow copy）。这意味着我们
        复制了字典本身，但字典中的值如果是可变对象（如列表、嵌套字典），
        它们仍然指向原始对象。对于配置字典这种简单场景，浅拷贝已经足够。
        使用 copy() 的目的是避免直接引用默认配置，防止后续修改污染原始默认值。
    """
    # 声明我们要修改模块级别的全局变量 _config
    # 没有 global 的话，_config = ... 会在函数内创建一个局部变量，外部看不到
    global _config

    # 检查配置是否尚未初始化（利用 None 作为哨兵值）
    # 【什么是哨兵值（Sentinel）？】用一个特殊值表示特殊状态。
    # 这里用 None 表示"还没初始化"，是一种常见的哨兵用法。
    # `is None` 是判断变量是否为 None 的标准写法（用 is 而不是 ==）
    if _config is None:
        # 复制默认配置，避免修改原始数据
        # default_config.DEFAULT_CONFIG 是默认配置字典
        # .copy() 创建副本，这样修改 _config 不会影响 default_config 里的原始默认值
        _config = default_config.DEFAULT_CONFIG.copy()


# ---------------------------------------------------------------------------
# 函数：set_config
# ---------------------------------------------------------------------------
def set_config(config: dict):
    """
    更新配置：使用自定义配置覆盖或合并到全局配置中。

    参数：
      config (Dict): 包含自定义配置项的字典。这些配置项会与已有配置合并。

    功能说明：
      如果全局配置尚未初始化，会先加载默认配置，然后用传入的自定义配置
      进行更新。这使得用户可以只传递需要修改的配置项，而不必提供完整的配置。
      这种"部分更新"的模式在配置管理中非常常见。

      【举个例子】
        默认配置：{"data_vendors": {...}, "cache_dir": "/tmp", "debug": False}
        用户调用：set_config({"debug": True})
        结果：只有 debug 变成 True，其他配置保持默认值不变。

    关键概念：
      - dict.update() 方法：
        将传入字典的键值对更新到目标字典中。如果传入的键在目标字典中已存在，
        则覆盖原有值；如果不存在，则添加新的键值对。
        例如：{'a': 1, 'b': 2}.update({'b': 3, 'c': 4}) 结果为 {'a': 1, 'b': 3, 'c': 4}
    """
    # 声明要修改全局变量
    global _config

    # 如果尚未初始化，先加载默认配置
    # 确保即使用户没有主动调用 initialize_config()，set_config 也能正常工作
    if _config is None:
        _config = default_config.DEFAULT_CONFIG.copy()

    # 用传入的自定义配置覆盖/合并到现有配置中
    # update() 会遍历 config 的每个键值对：
    #   - 如果键已存在于 _config 中，用新值覆盖旧值
    #   - 如果键不存在，添加新的键值对
    _config.update(config)


# ---------------------------------------------------------------------------
# 函数：get_config
# ---------------------------------------------------------------------------
def get_config() -> dict:
    """
    获取当前配置：返回当前全局配置的副本。

    返回值：
      Dict: 当前配置字典的浅拷贝。

    功能说明：
      如果配置尚未初始化，会先自动调用 initialize_config() 进行初始化。
      返回的是配置的副本而非原始引用，这样调用方修改返回的字典不会影响
      全局配置，保证了配置的封装性和安全性。

    关键概念：
      - 防御性拷贝（Defensive Copy）：
        返回 .copy() 而非直接返回 _config，可以防止外部代码意外修改全局配置。
        这是一种常见的防御性编程实践。
        【为什么需要防御性拷贝？】
          如果直接返回 _config，调用方可能不小心修改了它：
            cfg = get_config()
            cfg["data_vendors"] = {}  # 误操作！全局配置被改了！
          返回副本后，调用方修改的只是副本，原始全局配置不受影响。
      - 自动初始化：
        不需要显式调用 initialize_config()，get_config() 会自动处理。
        这种设计让使用方不必关心配置的初始化时机。
    """
    # 延迟初始化：如果配置未加载，先加载
    # 这保证了无论何时调用 get_config()，_config 一定不是 None
    if _config is None:
        initialize_config()

    # 返回副本，保护原始配置不被外部修改
    # 调用方拿到的是一份拷贝，修改它不会影响全局的 _config
    return _config.copy()


# ---------------------------------------------------------------------------
# 模块初始化
# ---------------------------------------------------------------------------

# 在模块被导入时自动执行一次初始化。
# 这确保了即使其他模块不主动调用 initialize_config()，配置也能被正确加载。
# 注意：由于 initialize_config() 内部有 if _config is None 检查，
# 多次调用也是安全的（幂等操作）。
#
# 【模块级代码什么时候执行？】
#   当 Python 第一次 import 这个模块时，会从头到尾执行模块内的代码。
#   这行代码会在 import 时执行，把 _config 初始化为默认配置。
#   之后再次 import 同一个模块时，Python 不会重新执行（模块只加载一次），
#   所以 _config 不会被重置。
initialize_config()
